import Foundation

/// The bureaucracy after a disaster, prepared by the agent from what it already knows:
/// a script for the emergency call and a pre-filled damage and needs report.
public enum Paperwork {
    public struct CallScript: Equatable, Sendable {
        public let number: String
        public let lines: [String]

        public var text: String { lines.joined(separator: " ") }
    }

    public struct Report: Equatable, Sendable {
        public struct Section: Equatable, Sendable {
            public let title: String
            public let rows: [String]
        }

        public let title: String
        public let generatedAt: Date
        public let sections: [Section]

        public var plainText: String {
            var text = "\(title)\n\(t("Generado por Faro el", "Generated by Faro on")) \(Paperwork.dateTime(generatedAt))\n"
            for section in sections {
                text += "\n\(section.title.uppercased())\n"
                text += section.rows.map { "• \($0)" }.joined(separator: "\n") + "\n"
            }
            return text
        }
    }

    // MARK: Call

    public static func callScript(profile: AgentProfile, state: MeshState, selfID: String, now: Date) -> CallScript {
        var lines = [t("Hola, mi nombre es \(profile.name).", "Hello, my name is \(profile.name).")]
        lines.append(t("Estoy en la zona de \(profile.homeArea), \(profile.country.displayName).", "I am in the \(profile.homeArea) area, \(profile.country.displayName)."))
        if profile.meetingPoint.isEmpty == false {
            lines.append(t("Un punto de referencia cercano es \(profile.meetingPoint).", "A nearby landmark is \(profile.meetingPoint)."))
        }
        let people = profile.housemates.count + 1
        lines.append(people == 1 ? t("Estoy solo en casa.", "I am alone at home.") : t("Somos \(people) personas en el hogar.", "There are \(people) people in my household."))

        for member in profile.housemates where member.isVulnerable {
            let needs = member.effectiveNeeds.map(\.displayName).joined(separator: t(" y ", " and ")).lowercased()
            if !needs.isEmpty {
                lines.append(t("Mi \(member.relation), \(member.name), depende de \(needs).", "My \(member.relation), \(member.name), relies on \(needs)."))
            }
            if !member.medical.isEmpty {
                lines.append("\(member.name): \(member.medical.summary).")
            }
        }
        for member in profile.household where !member.livesWithUser || !member.routine.isEmpty {
            let location = FamilyLocator.likelyLocation(of: member, at: now, homeArea: profile.homeArea)
            if location.place != t("Casa", "Home") {
                lines.append(t("\(member.name) probablemente está en \(location.description).", "\(member.name) is probably at \(location.description)."))
            }
        }

        let missing = unmetNeeds(profile: profile, state: state, selfID: selfID, now: now)
        if !missing.isEmpty {
            lines.append(t("Nos falta: \(missing.joined(separator: ", ")).", "We are missing: \(missing.joined(separator: ", "))."))
        }
        lines.append(t("No hay heridos que yo sepa.", "No one is injured as far as I know."))
        return CallScript(number: profile.country.emergencyNumber, lines: lines)
    }

    // MARK: Report

    public static func report(profile: AgentProfile, memory: AgentMemory, state: MeshState, selfID: String, now: Date) -> Report {
        var sections: [Report.Section] = []

        sections.append(.init(title: t("Persona que reporta", "Reported by"), rows: [
            "\(t("Nombre", "Name")): \(profile.name)",
            "\(t("Zona aproximada", "Approximate area")): \(profile.homeArea), \(profile.country.displayName)",
            "\(t("Contacto de familia", "Family contact")): \(profile.familyContacts.map { "\($0.name) (+\($0.phone))" }.joined(separator: ", ").ifEmpty(t("no registrado", "none")))"
        ]))

        var household = ["\(profile.name) (\(t("quien reporta", "reporter")))"]
        household += profile.housemates.map { member in
            member.effectiveNeeds.isEmpty
                ? "\(member.name), \(member.relation)"
                : "\(member.name), \(member.relation) — \(t("depende de", "relies on")) \(member.effectiveNeeds.map(\.displayName).joined(separator: t(" y ", " and ")).lowercased())"
        }
        sections.append(.init(title: t("Hogar (\(household.count) personas)", "Household (\(household.count) people)"), rows: household))

        let cards = profile.household.filter { !$0.medical.isEmpty }.map { member -> String in
            var line = "\(member.name): \(member.medical.summary)"
            if !member.medical.doctor.isEmpty { line += t(" · médico: \(member.medical.doctor)", " · doctor: \(member.medical.doctor)") }
            return line
        }
        if !cards.isEmpty {
            sections.append(.init(title: t("Fichas médicas", "Medical cards"), rows: cards))
        }
        let whereabouts = profile.household.filter { !$0.livesWithUser || !$0.routine.isEmpty }.map { member -> String in
            let location = FamilyLocator.likelyLocation(of: member, at: memory.emergencyStartedAt ?? now, homeArea: profile.homeArea)
            return "\(member.name): \(location.description) — \(location.reason)"
        }
        if !whereabouts.isEmpty {
            sections.append(.init(title: t("Dónde estaba cada familiar", "Where each relative was"), rows: whereabouts))
        }

        var event: [String] = []
        if let started = memory.emergencyStartedAt {
            event.append("\(t("Inicio de la emergencia", "Emergency started")): \(dateTime(started))")
        }
        if let cause = memory.log.last(where: { $0.kind == .mode && !$0.detail.isEmpty })?.detail {
            event.append("\(t("Cómo se detectó", "How it was detected")): \(cause)")
        }
        let quakes = state.seismicReports.filter { abs($0.detectedAt.timeIntervalSince(memory.emergencyStartedAt ?? now)) < 600 }
        if !quakes.isEmpty {
            let peak = quakes.map(\.peakAcceleration).max() ?? 0
            event.append(t("Teléfonos cercanos que sintieron el movimiento: \(Set(quakes.map(\.deviceID)).count) (pico \(String(format: "%.2f", peak)) g)", "Nearby phones that felt the shaking: \(Set(quakes.map(\.deviceID)).count) (peak \(String(format: "%.2f", peak)) g)"))
        }
        sections.append(.init(title: t("Evento", "Event"), rows: event.ifEmpty([t("Sin datos del evento.", "No event data.")])))

        let missing = unmetNeeds(profile: profile, state: state, selfID: selfID, now: now)
        sections.append(.init(title: t("Necesidades sin cubrir", "Unmet needs"), rows: missing.ifEmpty([t("Ninguna registrada.", "None recorded.")])))

        let received = agreements(state: state, selfID: selfID).map { line in
            line.delivered ? "\(line.text) — \(t("entregado", "delivered"))" : "\(line.text) — \(t("acordado", "agreed"))"
        }
        sections.append(.init(title: t("Ayuda coordinada entre vecinos", "Help coordinated with neighbors"), rows: received.ifEmpty([t("Ninguna todavía.", "None yet.")])))

        let timeline = memory.log
            .filter { [.mode, .checkIn, .published, .agreement, .family].contains($0.kind) }
            .reversed()
            .prefix(12)
            .map { "\(time($0.date)) — \($0.title)" }
        sections.append(.init(title: t("Cronología", "Timeline"), rows: Array(timeline).ifEmpty([t("Sin acciones registradas.", "No actions recorded.")])))

        sections.append(.init(title: t("Nota", "Note"), rows: [
            t("Preparado por un agente personal con datos de la persona. Sin direcciones exactas.", "Prepared by a personal agent from the person's own data. No exact addresses."),
            t("Revísalo antes de enviarlo a autoridades, aseguradora o registro de damnificados.", "Review it before sending it to authorities, an insurer or a disaster registry.")
        ]))

        return Report(title: t("Reporte de afectación del hogar", "Household damage report"), generatedAt: now, sections: sections)
    }

    // MARK: Helpers

    static func unmetNeeds(profile: AgentProfile, state: MeshState, selfID: String, now: Date) -> [String] {
        state.posts
            .filter { $0.authorID == selfID && $0.kind == .need && $0.isActive(at: now) }
            .compactMap { need in
                let covered = state.proposals
                    .filter { $0.needID == need.id }
                    .compactMap { state.negotiation(for: $0.id).agreedTerms?.quantity }
                    .reduce(0, +)
                let missing = need.quantity - covered
                return missing > 0 ? need.resource.amount(missing) : nil
            }
    }

    struct AgreementLine {
        let text: String
        let delivered: Bool
    }

    static func agreements(state: MeshState, selfID: String) -> [AgreementLine] {
        state.proposals.compactMap { proposal in
            guard let terms = state.negotiation(for: proposal.id).agreedTerms,
                  let need = state.posts.first(where: { $0.id == proposal.needID }),
                  let offer = state.posts.first(where: { $0.id == proposal.offerID }),
                  need.authorID == selfID || offer.authorID == selfID else { return nil }
            let text = need.authorID == selfID
                ? t("Recibimos \(need.resource.amount(terms.quantity)) de \(offer.authorName)", "We received \(need.resource.amount(terms.quantity)) from \(offer.authorName)")
                : t("Entregamos \(need.resource.amount(terms.quantity)) a \(need.authorName)", "We gave \(need.resource.amount(terms.quantity)) to \(need.authorName)")
            return AgreementLine(text: text, delivered: proposal.completions.contains(selfID))
        }
    }

    /// "1 botella", "3 botellas".
    public static func quantity(_ value: Int, _ unit: String) -> String {
        guard value == 1 else { return "\(value) \(unit)" }
        let singular = unit.hasSuffix("es") && unit.count > 4 && !unit.hasSuffix("tes")
            ? String(unit.dropLast(2))
            : unit.hasSuffix("s") ? String(unit.dropLast()) : unit
        return "1 \(singular)"
    }

    static func dateTime(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.locale = Lang.current.locale
        formatter.dateFormat = Lang.isSpanish ? "d 'de' MMMM, HH:mm" : "MMMM d, HH:mm"
        return formatter.string(from: date)
    }

    static func time(_ date: Date) -> String {
        PersonalAgent.timeFormatter.string(from: date)
    }
}

private extension String {
    func ifEmpty(_ fallback: String) -> String { isEmpty ? fallback : self }
}

private extension Array {
    func ifEmpty(_ fallback: [Element]) -> [Element] { isEmpty ? fallback : self }
}
